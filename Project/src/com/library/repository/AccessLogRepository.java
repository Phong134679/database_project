package com.library.repository;

import com.library.model.AccessLog;
import com.library.util.DatabaseConnection;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Repository class handling MySQL data persistence for ACCESS_LOG entity.
 * Implements high-throughput decoupled logging according to BR13 and FR08.
 */
public class AccessLogRepository {

    /**
     * Inserts an access log entry into ACCESS_LOG and updates logId.
     */
    public void insertLog(AccessLog log) {
        String sql = "INSERT INTO ACCESS_LOG (person_id, journal_resource_id, access_timestamp, ip_address, download_success) " +
                     "VALUES (?, ?, ?, ?, ?)";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setInt(1, log.getPersonId());
            ps.setInt(2, log.getJournalResourceId());
            LocalDateTime ts = log.getAccessTimestamp() != null ? log.getAccessTimestamp() : LocalDateTime.now();
            ps.setTimestamp(3, Timestamp.valueOf(ts));
            ps.setString(4, log.getIpAddress());
            ps.setBoolean(5, log.isDownloadSuccess());

            int affectedRows = ps.executeUpdate();
            if (affectedRows > 0) {
                try (ResultSet generatedKeys = ps.getGeneratedKeys()) {
                    if (generatedKeys.next()) {
                        log.setLogId(generatedKeys.getLong(1));
                    }
                }
            }
        } catch (SQLException e) {
            System.err.println("[AccessLogRepository] Error inserting access log: " + e.getMessage());
        }
    }

    /**
     * Finds an access log by logId.
     */
    public AccessLog findById(long logId) {
        String sql = "SELECT log_id, person_id, journal_resource_id, access_timestamp, ip_address, download_success " +
                     "FROM ACCESS_LOG WHERE log_id = ?";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setLong(1, logId);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return mapRowToLog(rs);
                }
            }
        } catch (SQLException e) {
            System.err.println("[AccessLogRepository] Error finding log " + logId + ": " + e.getMessage());
        }
        return null;
    }

    /**
     * Retrieves all access logs generated by a specific person.
     */
    public List<AccessLog> findByPersonId(int personId) {
        List<AccessLog> list = new ArrayList<>();
        String sql = "SELECT log_id, person_id, journal_resource_id, access_timestamp, ip_address, download_success " +
                     "FROM ACCESS_LOG WHERE person_id = ? ORDER BY access_timestamp DESC";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, personId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    list.add(mapRowToLog(rs));
                }
            }
        } catch (SQLException e) {
            System.err.println("[AccessLogRepository] Error finding logs for person " + personId + ": " + e.getMessage());
        }
        return list;
    }

    /**
     * Retrieves all access logs for a specific digital journal.
     */
    public List<AccessLog> findByJournalId(int journalResourceId) {
        List<AccessLog> list = new ArrayList<>();
        String sql = "SELECT log_id, person_id, journal_resource_id, access_timestamp, ip_address, download_success " +
                     "FROM ACCESS_LOG WHERE journal_resource_id = ? ORDER BY access_timestamp DESC";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, journalResourceId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    list.add(mapRowToLog(rs));
                }
            }
        } catch (SQLException e) {
            System.err.println("[AccessLogRepository] Error finding logs for journal " + journalResourceId + ": " + e.getMessage());
        }
        return list;
    }

    /**
     * Retrieves all access logs.
     */
    public List<AccessLog> findAll() {
        List<AccessLog> list = new ArrayList<>();
        String sql = "SELECT log_id, person_id, journal_resource_id, access_timestamp, ip_address, download_success " +
                     "FROM ACCESS_LOG ORDER BY access_timestamp DESC";
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                list.add(mapRowToLog(rs));
            }
        } catch (SQLException e) {
            System.err.println("[AccessLogRepository] Error fetching all logs: " + e.getMessage());
        }
        return list;
    }

    private AccessLog mapRowToLog(ResultSet rs) throws SQLException {
        Timestamp ts = rs.getTimestamp("access_timestamp");
        return new AccessLog(
                rs.getLong("log_id"),
                rs.getInt("person_id"),
                rs.getInt("journal_resource_id"),
                ts != null ? ts.toLocalDateTime() : null,
                rs.getString("ip_address"),
                rs.getBoolean("download_success")
        );
    }
}
